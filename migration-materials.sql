-- 7.9.0 — «سجل المواد»: جدول بسيط (المادة · مواصفاتها بسطر واحد · الحالة) يظهر أعلى المكتبة.
-- مخفي افتراضيًا: site_settings.materials_on = false حتى يفعّله الأدمن من لوحة الإدارة. آمن لإعادة التشغيل.
alter table public.site_settings
  add column if not exists materials_on boolean not null default false,
  add column if not exists materials_pdf boolean not null default true; -- زر «تنزيل PDF» للزوار: مفتاح مستقل
grant select (materials_on, materials_pdf) on public.site_settings to anon, authenticated;
grant update (materials_on, materials_pdf) on public.site_settings to authenticated;

create table if not exists public.materials (
  id bigint generated by default as identity primary key,
  name text not null,
  spec text not null default '',
  status text not null default 'مرصودة',
  ref_url text,
  media_id bigint references public.media_items(id) on delete set null, -- ربط بملف من المكتبة: الرابط يتبع الملف تلقائيًا
  sort_order integer not null default 0,
  updated_at timestamptz not null default now(),
  constraint materials_status_chk check (status in ('مرصودة', 'معتمدة', 'قيد الدراسة'))
);
alter table public.materials enable row level security;
grant select on public.materials to anon, authenticated;
grant insert, update, delete on public.materials to authenticated;

drop policy if exists "قراءة عامة - سجل المواد" on public.materials;
create policy "قراءة عامة - سجل المواد" on public.materials for select to anon, authenticated
  using ((select s.materials_on from public.site_settings s where s.id = 1) and (select gate_ok(variadic array['gallery'::text])));
drop policy if exists "قراءة الإدارة - سجل المواد" on public.materials;
create policy "قراءة الإدارة - سجل المواد" on public.materials for select to authenticated
  using (has_perm('manage_gallery'::text));
drop policy if exists "إضافة - سجل المواد" on public.materials;
create policy "إضافة - سجل المواد" on public.materials for insert to authenticated
  with check (has_perm('manage_gallery'::text));
drop policy if exists "تعديل - سجل المواد" on public.materials;
create policy "تعديل - سجل المواد" on public.materials for update to authenticated
  using (has_perm('manage_gallery'::text)) with check (has_perm('manage_gallery'::text));
drop policy if exists "حذف - سجل المواد" on public.materials;
create policy "حذف - سجل المواد" on public.materials for delete to authenticated
  using (has_perm('manage_gallery'::text));
