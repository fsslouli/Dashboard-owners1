-- ٢) سجل النسخ
create table if not exists public.workbook_versions (
  id bigint generated by default as identity primary key,
  version_no integer not null unique,
  file_name text not null,
  storage_path text not null unique,
  size_bytes bigint not null default 0,
  sha256 text,
  sheet_names jsonb not null default '[]'::jsonb,
  inquiry_count integer,
  note text not null default '',
  source text not null default 'admin',
  uploaded_by uuid,
  uploaded_by_name text not null default '',
  created_at timestamptz not null default now(),
  constraint workbook_versions_source_chk check (source in ('admin', 'assistant'))
);
alter table public.workbook_versions enable row level security;
grant select on public.workbook_versions to authenticated;

do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'workbook_versions' and policyname = 'قراءة - ملف الإكسل') then
    create policy "قراءة - ملف الإكسل" on public.workbook_versions for select to authenticated using (has_perm('import_excel'::text));
  end if;
end $$;
-- ما فيه سياسة إضافة/تعديل/حذف: التسجيل فقط عبر workbook_register() أو دالة المساعد (service role).

-- ٣) تسجيل نسخة رفعها الأدمن من اللوحة
create or replace function public.workbook_register(
  p_path text, p_file_name text, p_size bigint, p_sha256 text,
  p_sheet_names jsonb, p_inquiry_count integer, p_note text
) returns public.workbook_versions
language plpgsql security definer set search_path = public as $$
declare r public.workbook_versions; v_name text;
begin
  -- coalesce: has_perm ترجع NULL لحساب ما له صف بجدول profiles (زائر أو حساب فيلا)، فنعتبرها «لا»
  if not coalesce(has_perm('import_excel'), false) then raise exception 'forbidden'; end if;
  if p_path is null or p_path !~ '^admin/[0-9a-f-]{36}\.xlsx$' then raise exception 'bad_path'; end if;
  if not exists (select 1 from storage.objects o where o.bucket_id = 'workbook' and o.name = p_path
                 and (o.owner = auth.uid() or o.owner_id = auth.uid()::text)) then
    raise exception 'file_missing';
  end if;
  perform pg_advisory_xact_lock(hashtext('workbook_versions'));
  select coalesce(nullif(trim(p.name), ''), '') into v_name from public.profiles p where p.id = auth.uid();
  insert into public.workbook_versions (version_no, file_name, storage_path, size_bytes, sha256, sheet_names,
                                        inquiry_count, note, source, uploaded_by, uploaded_by_name)
  values ((select coalesce(max(version_no), 0) + 1 from public.workbook_versions),
          left(coalesce(nullif(trim(p_file_name), ''), 'workbook.xlsx'), 200), p_path, coalesce(p_size, 0), p_sha256,
          case when jsonb_typeof(p_sheet_names) = 'array' then p_sheet_names else '[]'::jsonb end,
          p_inquiry_count, left(coalesce(p_note, ''), 500), 'admin', auth.uid(), coalesce(v_name, ''))
  returning * into r;
  return r;
end $$;
grant execute on function public.workbook_register(text, text, bigint, text, jsonb, integer, text) to authenticated;

-- ٤) صلاحيات الخزنة: قراءة ورفع للإدارة فقط (بدون تعديل أو حذف)
do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects' and policyname = 'قراءة - ملف الإكسل الرئيسي') then
    create policy "قراءة - ملف الإكسل الرئيسي" on storage.objects for select to authenticated
      using (bucket_id = 'workbook' and has_perm('import_excel'::text));
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects' and policyname = 'رفع - ملف الإكسل الرئيسي') then
    create policy "رفع - ملف الإكسل الرئيسي" on storage.objects for insert to authenticated
      with check (bucket_id = 'workbook' and (storage.foldername(name))[1] = 'admin' and has_perm('import_excel'::text));
  end if;
end $$;

